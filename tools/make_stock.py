#!/usr/bin/env python3
"""Builds the bundled starter pack in stock/. Everything is generated here with FFmpeg's
own synthetic sources (gradients, patterns, sine tones), so it is original to this project and
released under CC0 1.0. No third-party media. Run: python3 tools/make_stock.py"""
import json, os, subprocess, sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "stock")
os.makedirs(OUT, exist_ok=True)
AUTHOR = "Lite Editor project"
LIC = "CC0 1.0 (generated for this project)"
LIC_URL = "https://creativecommons.org/publicdomain/zero/1.0/"

def ff(*args):
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("ffmpeg failed: %s\n%s" % (" ".join(cmd), r.stderr))

items = []

def thumb(src, name, at=0.5):
    seek = ["-ss", str(at)] if at else []  # seeking inside a one-frame image yields no output
    ff(*seek, "-i", src, "-frames:v", "1", "-vf", "scale=-2:96", "-q:v", "6", os.path.join(OUT, name))
    if not os.path.exists(os.path.join(OUT, name)):
        sys.exit("thumbnail was not written: " + name)

def add(kind, id_, title, category, file, thumbf=None, dur=None, tags=""):
    it = {"id": id_, "kind": kind, "title": title, "category": category, "file": file,
          "author": AUTHOR, "licence": LIC, "licence_url": LIC_URL, "source": "generated by tools/make_stock.py"}
    if thumbf: it["thumb"] = thumbf
    if dur: it["dur"] = dur
    items.append(it)

W, H, R, D = 1280, 720, 24, 6
vcodec = ["-c:v", "libvpx", "-b:v", "1800k", "-crf", "12", "-deadline", "good", "-cpu-used", "4", "-pix_fmt", "yuv420p", "-an"]

videos = [
    ("v-aurora", "Aurora drift", "Backgrounds",
     f"gradients=s={W}x{H}:r={R}:d={D}:c0=0x0b1d3a:c1=0x1fa88a:c2=0x6a4fe0:c3=0x0b1d3a:x0=0:y0=0:x1={W}:y1={H}:speed=0.02:nb_colors=4,gblur=sigma=18"),
    ("v-ember", "Ember glow", "Backgrounds",
     f"gradients=s={W}x{H}:r={R}:d={D}:c0=0x2b0a12:c1=0xe8590c:c2=0xffd43b:c3=0x2b0a12:x0=0:y0={H}:x1={W}:y1=0:speed=0.03:nb_colors=4,gblur=sigma=22"),
    ("v-tide", "Slow tide", "Backgrounds",
     f"gradients=s={W}x{H}:r={R}:d={D}:c0=0x04202e:c1=0x1b7ea0:c2=0x9bd7e8:c3=0x04202e:x0=0:y0=0:x1=0:y1={H}:speed=0.025:nb_colors=4,gblur=sigma=14"),
    ("v-fractal", "Fractal bloom", "Abstract",
     f"mandelbrot=s={W}x{H}:r={R}:maxiter=120:start_scale=1.4:end_scale=0.05:end_pts={D*24},hue=h=t*40,format=yuv420p"),
    ("v-cells", "Living cells", "Abstract",
     f"life=s=160x90:r={R}:ratio=0.18:death_color=0x0a0f1e:life_color=0x7bf1a8:mold_color=0x2b6cb0:mold=8:random_seed=7,scale={W}:{H}:flags=neighbor,gblur=sigma=3"),
    ("v-zone", "Zone rings", "Abstract",
     f"zoneplate=s={W}x{H}:r={R}:d={D}:k0=5:kx=2:ky=2:kt=3:precision=10,hue=s=0.3,eq=contrast=1.2"),
]
for id_, title, cat, src in videos:
    f = id_ + ".webm"
    ff("-f", "lavfi", "-i", src, "-t", str(D), *vcodec, os.path.join(OUT, f))
    t = id_ + ".jpg"
    thumb(os.path.join(OUT, f), t, 1.0)
    add("video", id_, title, cat, f, t, D * 1_000_000)

images = [
    ("i-dusk", "Dusk gradient", "Backgrounds", "0x1a1038", "0xff7a59"),
    ("i-mint", "Mint paper", "Backgrounds", "0xe3f6ec", "0x7fd1ae"),
    ("i-ink", "Ink wash", "Backgrounds", "0x0a0a12", "0x3a3f66"),
    ("i-sun", "Sunrise", "Backgrounds", "0x3a1c71", "0xffaf7b"),
]
for id_, title, cat, c0, c1 in images:
    f = id_ + ".jpg"
    ff("-f", "lavfi", "-i", f"gradients=s=1920x1080:c0={c0}:c1={c1}:x0=0:y0=0:x1=1920:y1=1080:nb_colors=2:seed=3", "-frames:v", "1", "-q:v", "3", os.path.join(OUT, f))
    thumb(os.path.join(OUT, f), id_ + "-t.jpg", 0)
    add("image", id_, title, cat, f, id_ + "-t.jpg")

# ---- audio: simple synthesized loops and effects (sine/noise based, 10 s or less)
def tone_chain(freqs, secs, vol=0.25):
    return "+".join(f"{vol/len(freqs):.3f}*sin(2*PI*{f}*t)" for f in freqs)

audio = [
    ("a-calm", "Calm pads", "Music", "aevalsrc='(" + tone_chain([220, 277.18, 329.63], 12) + ")*(0.6+0.4*sin(2*PI*0.15*t))':d=12:s=44100"),
    ("a-bright", "Bright arp", "Music", "aevalsrc='0.22*sin(2*PI*(440+110*floor(mod(t*4,4)))*t)*exp(-mod(t*4,1)*4)':d=12:s=44100"),
    ("a-pulse", "Low pulse", "Music", "aevalsrc='0.35*sin(2*PI*55*t)*exp(-mod(t*2,1)*6)+0.08*sin(2*PI*110*t)':d=12:s=44100"),
    ("s-whoosh", "Whoosh", "Sound effects", "anoisesrc=d=1.2:c=pink:a=0.5:r=44100,lowpass=f=1800,afade=t=in:d=0.5,afade=t=out:st=0.6:d=0.6"),
    ("s-click", "Soft click", "Sound effects", "aevalsrc='0.5*sin(2*PI*1800*t)*exp(-t*90)':d=0.25:s=44100"),
    ("s-chime", "Chime", "Sound effects", "aevalsrc='0.3*(sin(2*PI*880*t)+0.5*sin(2*PI*1320*t))*exp(-t*3)':d=2:s=44100"),
]
for id_, title, cat, src in audio:
    f = id_ + ".ogg"
    ff("-f", "lavfi", "-i", src, "-c:a", "libvorbis", "-q:a", "3", os.path.join(OUT, f))
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", os.path.join(OUT, f)], capture_output=True, text=True).stdout.strip()
    add("audio", id_, title, cat, f, None, int(float(out) * 1_000_000))

with open(os.path.join(OUT, "index.json"), "w") as fh:
    json.dump(items, fh, indent=1)
with open(os.path.join(OUT, "LICENSE.txt"), "w") as fh:
    fh.write("Starter media in this folder was generated by tools/make_stock.py using FFmpeg's built-in\nsynthetic sources. It is original to this project and released under CC0 1.0 Universal:\nhttps://creativecommons.org/publicdomain/zero/1.0/\nNo third-party media is included.\n")
print(len(items), "items,", sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) // 1024, "KB")
